#!/usr/bin/env python3
"""
Export MAVLink v2 message + enum definitions from pymavlink into a JavaScript
module, so the browser simulator can build byte-exact MAVLink frames
(same wire order, CRC_EXTRA and struct format that pymavlink/mavutil use).

    pip install pymavlink
    python tools/gen_mavlink_defs.py > js/mavlink-defs.js             # simulator subset
    python tools/gen_mavlink_defs.py --all > js/mavlink-defs-full.js  # whole dialect (log viewer)
"""
import json
import re
import sys

from pymavlink.dialects.v20 import ardupilotmega as mav

# Messages the simulator emits (common.xml + ardupilotmega.xml)
MESSAGES = [
    "HEARTBEAT", "SYS_STATUS", "SYSTEM_TIME", "SET_MODE",
    "PARAM_REQUEST_LIST", "PARAM_VALUE", "PARAM_SET",
    "GPS_RAW_INT", "ATTITUDE", "GLOBAL_POSITION_INT", "SERVO_OUTPUT_RAW",
    "MISSION_REQUEST", "MISSION_SET_CURRENT", "MISSION_CURRENT",
    "MISSION_REQUEST_LIST", "MISSION_COUNT", "MISSION_CLEAR_ALL",
    "MISSION_ITEM_REACHED", "MISSION_ACK", "GPS_GLOBAL_ORIGIN",
    "MISSION_REQUEST_INT", "RC_CHANNELS", "REQUEST_DATA_STREAM",
    "MISSION_ITEM_INT", "VFR_HUD", "COMMAND_LONG", "COMMAND_ACK",
    "BATTERY_STATUS", "AUTOPILOT_VERSION", "CAMERA_FEEDBACK",
    "EKF_STATUS_REPORT", "HOME_POSITION", "STATUSTEXT",
]

ENUMS = [
    "MAV_TYPE", "MAV_AUTOPILOT", "MAV_MODE_FLAG", "MAV_STATE", "MAV_CMD",
    "MAV_RESULT", "MAV_SEVERITY", "MAV_FRAME", "MAV_MISSION_RESULT",
    "MAV_MISSION_TYPE", "MAV_PARAM_TYPE", "GPS_FIX_TYPE", "COPTER_MODE",
    "MAV_BATTERY_FUNCTION", "MAV_BATTERY_TYPE", "MAV_BATTERY_CHARGE_STATE",
    "MAV_DATA_STREAM", "MAV_SYS_STATUS_SENSOR", "EKF_STATUS_FLAGS",
    "MAV_PROTOCOL_CAPABILITY", "CAMERA_FEEDBACK_FLAGS", "MISSION_STATE",
]

TOKEN = re.compile(r"(\d*)([a-zA-Z?])")


def message_def(name):
    cls = getattr(mav, "MAVLink_%s_message" % name.lower())
    fmt = cls.unpacker.format
    if isinstance(fmt, bytes):
        fmt = fmt.decode()
    tokens = TOKEN.findall(fmt.lstrip("<"))
    assert len(tokens) == len(cls.ordered_fieldnames), name
    ftypes = dict(zip(cls.fieldnames, cls.fieldtypes))
    wire = []
    for fname, (count, code) in zip(cls.ordered_fieldnames, tokens):
        wire.append({
            "name": fname,
            "type": ftypes[fname],
            "fmt": code,                      # struct code (B,b,H,h,I,i,Q,q,f,d,s)
            "len": int(count) if count else 0,  # array / char[] length
        })
    return {
        "id": cls.id,
        "name": cls.msgname,
        "crc_extra": cls.crc_extra,
        "fields": list(cls.fieldnames),   # display order (as printed by pymavlink)
        "wire": wire,                     # payload order on the wire
        "enums": dict(cls.fieldenums_by_name),
        "units": dict(cls.fieldunits_by_name),
        "display": dict(cls.fielddisplays_by_name),
    }


def enum_def(name):
    out = {}
    for value, entry in mav.enums[name].items():
        if entry.name.endswith("_ENUM_END"):
            continue
        desc = " ".join((entry.description or "").split())
        out[str(value)] = [entry.name, desc[:220]]
    return out


def main():
    full = "--all" in sys.argv
    messages = sorted(cls.msgname for cls in mav.mavlink_map.values()) if full else MESSAGES
    enums = sorted(mav.enums) if full else ENUMS
    data = {
        "source": "pymavlink %s, dialect ardupilotmega (MAVLink 2)" % getattr(
            __import__("pymavlink"), "__version__", ""),
        "messages": {n: message_def(n) for n in messages},
        "enums": {n: enum_def(n) for n in enums if n in mav.enums},
    }
    sys.stdout.write("// AUTO-GENERATED by tools/gen_mavlink_defs.py from pymavlink. Do not edit.\n")
    sys.stdout.write("export const MAVLINK_DEFS%s = " % ("_FULL" if full else ""))
    json.dump(data, sys.stdout, separators=(",", ":"))
    sys.stdout.write(";\n")


if __name__ == "__main__":
    main()
